<?php
declare(strict_types=1);
$dir = __DIR__ . DIRECTORY_SEPARATOR . 'data';
$file = $dir . DIRECTORY_SEPARATOR . 'nowpayments-config.php';
if (!is_dir($dir)) @mkdir($dir, 0755, true);
$already = is_file($file);
$message = '';
$error = '';

if ($_SERVER['REQUEST_METHOD'] === 'POST' && !$already) {
    $apiKey = trim((string)($_POST['api_key'] ?? ''));
    $ipnSecret = trim((string)($_POST['ipn_secret'] ?? ''));
    $publicUrl = rtrim(trim((string)($_POST['public_url'] ?? '')), '/');

    if (strlen($apiKey) < 12) {
        $error = 'Enter your NOWPayments API key.';
    } elseif (strlen($ipnSecret) < 12) {
        $error = 'Enter your NOWPayments IPN secret key.';
    } elseif ($publicUrl !== '' && !filter_var($publicUrl, FILTER_VALIDATE_URL)) {
        $error = 'The public site URL is not valid.';
    } else {
        $config = [
            'api_key' => $apiKey,
            'ipn_secret' => $ipnSecret,
            'public_url' => $publicUrl,
        ];
        $content = "<?php\n// Generated by setup-payments.php. Keep private and never commit this file.\nreturn " . var_export($config, true) . ";\n";
        if (file_put_contents($file, $content, LOCK_EX) === false) {
            $error = 'Could not write data/nowpayments-config.php. Make sure the data folder is writable.';
        } else {
            @chmod($file, 0640);
            $already = true;
            $message = 'NOWPayments credentials saved. Crypto checkout is ready.';
        }
    }
}
?>
<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width,initial-scale=1">
  <meta name="robots" content="noindex,nofollow">
