  </style>
</head>
<body>
<main class="setup-wrap">
  <div class="setup-card">
    <p class="eyebrow">Payment setup</p>
    <h1>Connect NOWPayments</h1>
    <?php if ($message): ?><p class="setup-msg setup-ok"><?= htmlspecialchars($message) ?></p><?php endif; ?>
    <?php if ($error): ?><p class="setup-msg setup-err"><?= htmlspecialchars($error) ?></p><?php endif; ?>

    <?php if ($already): ?>
      <p>NOWPayments has already been configured on this server. This setup page is locked.</p>
      <p><a class="button" href="index.html">Go to the donation page</a></p>
      <p><small>To intentionally replace the credentials later, delete <code>data/nowpayments-config.php</code> from your own server and revisit this page.</small></p>
    <?php else: ?>
      <p>Your API credentials are stored only on the PHP server and are never sent to visitors' browsers.</p>
      <form method="post" autocomplete="off">
        <label>NOWPayments API key
          <input type="password" name="api_key" required autocomplete="off">
          <small>NOWPayments Dashboard → API Settings → Add new key.</small>
        </label>
        <label>IPN secret key
          <input type="password" name="ipn_secret" required autocomplete="off">
          <small>Generate this in NOWPayments Store Settings. Save it carefully because NOWPayments may display it only once.</small>
        </label>
        <label>Public website URL <span style="font-weight:400">(optional while using XAMPP)</span>
          <input type="url" name="public_url" placeholder="https://yourdomain.com">
          <small>After moving to Hostinger, set this to the live site URL so NOWPayments can send payment-status callbacks to your website.</small>
        </label>
        <button class="button" type="submit">Save NOWPayments settings</button>
      </form>
    <?php endif; ?>
  </div>
</main>
</body>
</html>
